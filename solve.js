/** A template that does not parse: its name and why. */
class TemplateError extends Error {}

const TPATH = /^[A-Za-z_][A-Za-z0-9_]*(?:\.[A-Za-z_][A-Za-z0-9_]*)*$/;
const TFOR = /^for ([A-Za-z_][A-Za-z0-9_]*) in (\S+)$/;
const TIF = /^if (not )?(\S+)$/;
const TINCLUDE = /^include "([a-z0-9-]+)"$/;

/** The path `text` names, split at its dots, or a TemplateError. */
function pathOf(name, text) {
  if (!TPATH.test(text)) throw new TemplateError(`template "${name}": ${JSON.stringify(text)} is not a path`);
  return text.split('.');
}

/** `src`'s tokens: text, {{ }}, {{{ }}} and {% %}, a standalone tag's line taken with it. */
function tokenize(name, src) {
  const tokens = [];
  let text = '';
  let i = 0;
  while (i < src.length) {
    const open = src.indexOf('{', i);
    if (open === -1 || open === src.length - 1) {
      text += src.slice(i);
      break;
    }
    const next = src[open + 1];
    if (next !== '{' && next !== '%') {
      text += src.slice(i, open + 1);
      i = open + 1;
      continue;
    }
    text += src.slice(i, open);
    if (next === '{') {
      const raw = src[open + 2] === '{';
      const close = src.indexOf(raw ? '}}}' : '}}', open + (raw ? 3 : 2));
      if (close === -1) throw new TemplateError(`template "${name}": a ${raw ? '{{{' : '{{'} is not closed`);
      if (text !== '') tokens.push({ t: 'text', text });
      text = '';
      tokens.push({ t: raw ? 'raw' : 'var', path: pathOf(name, src.slice(open + (raw ? 3 : 2), close).trim()) });
      i = close + (raw ? 3 : 2);
      continue;
    }
    const close = src.indexOf('%}', open + 2);
    if (close === -1) throw new TemplateError(`template "${name}": a {% is not closed`);
    const end = close + 2;
    const lineStart = src.lastIndexOf('\n', open - 1) + 1;
    const nl = src.indexOf('\n', end);
    const lineEnd = nl === -1 ? src.length : nl;
    const standalone = /^[ \t]*$/.test(src.slice(lineStart, open)) && /^[ \t]*$/.test(src.slice(end, lineEnd));
    if (standalone) text = text.slice(0, text.length - (open - lineStart));
    if (text !== '') tokens.push({ t: 'text', text });
    text = '';
    tokens.push({ t: 'tag', tag: src.slice(open + 2, close).trim() });
    i = standalone ? (nl === -1 ? src.length : nl + 1) : end;
  }
  if (text !== '') tokens.push({ t: 'text', text });
  return tokens;
}

/** `src` parsed into its tree of nodes (a TemplateError when it does not parse). */
function parseTemplate(name, src) {
  const root = { kind: 'root', body: [] };
  const stack = [root];
  let body = root.body;
  for (const tok of tokenize(name, src)) {
    if (tok.t === 'text') body.push({ kind: 'text', text: tok.text });
    else if (tok.t === 'var' || tok.t === 'raw') body.push({ kind: tok.t, path: tok.path });
    else {
      const tag = tok.tag;
      const top = stack[stack.length - 1];
      let m;
      if ((m = TFOR.exec(tag)) !== null) {
        const node = { kind: 'for', name: m[1], path: pathOf(name, m[2]), body: [] };
        body.push(node);
        stack.push(node);
        body = node.body;
      } else if ((m = TIF.exec(tag)) !== null) {
        const node = { kind: 'if', not: m[1] !== undefined, path: pathOf(name, m[2]), then: [], else: null };
        body.push(node);
        stack.push(node);
        body = node.then;
      } else if (tag === 'else') {
        if (top.kind !== 'if' || top.else !== null) throw new TemplateError(`template "${name}": an else outside an if`);
        top.else = [];
        body = top.else;
      } else if (tag === 'endfor' || tag === 'endif') {
        if (top.kind !== (tag === 'endfor' ? 'for' : 'if')) throw new TemplateError(`template "${name}": an ${tag} with no open ${tag.slice(3)}`);
        stack.pop();
        const parent = stack[stack.length - 1];
        body = parent.kind === 'root' ? parent.body : parent.kind === 'for' ? parent.body : parent.else ?? parent.then;
      } else if ((m = TINCLUDE.exec(tag)) !== null) body.push({ kind: 'include', name: m[1] });
      else throw new TemplateError(`template "${name}": {% ${tag} %} is not a tag`);
    }
  }
  if (stack.length > 1) throw new TemplateError(`template "${name}": a ${stack[stack.length - 1].kind} is not closed`);
  return root.body;
}

/** A value as text: a string itself, a number in JavaScript's digits, true or false, an array's items joined by ", ", else "". */
function textOf(v) {
  if (typeof v === 'string') return v;
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (Array.isArray(v)) return v.map(textOf).join(', ');
  return '';
}

/** Whether a value counts as true in an if: not undefined, null, false, "", 0 or an empty array. */
function truthy(v) {
  if (Array.isArray(v)) return v.length > 0;
  return v !== undefined && v !== null && v !== false && v !== '' && v !== 0;
}

/** `escapeHtml(textOf(v))`: a value written escaped, as {{ }} writes it. */
function escText(v) {
  if (typeof v === 'string') return esc(v);
  return esc(textOf(v));
}

/** The loop value a for body that never reads `loop` sees (an object, so {% if loop %} stays true). */
const EMPTY_LOOP = Object.freeze({});

/**
 * Whether `nodes` read the name `loop` in the current scope: a var, raw or
 * if path opening on it, a for path opening on it, or an include (to the
 * depth the compiler inlines) that does. A for body's own reads are shadowed
 * by that for's loop, so its body is not walked.
 */
function refsLoop(nodes, depth, templates) {
  for (const n of nodes) {
    if (n.kind === 'var' || n.kind === 'raw') {
      if (n.path[0] === 'loop') return true;
    } else if (n.kind === 'if') {
      if (n.path[0] === 'loop') return true;
      if (refsLoop(n.then, depth, templates)) return true;
      if (n.else !== null && refsLoop(n.else, depth, templates)) return true;
    } else if (n.kind === 'for') {
      if (n.path[0] === 'loop') return true;
    } else if (n.kind === 'include') {
      const t = templates.get(n.name);
      if (t !== undefined && depth < 8 && refsLoop(t, depth + 1, templates)) return true;
    }
  }
  return false;
}

/**
 * Compile a parsed template into a function (V, esc, textOf, truthy) -> string.
 * Includes are inlined (at most 8 deep); a path's first name is resolved
 * from the innermost loop that binds it, else from V; later names use ?.
 * Scopes are resolved at compile time, so rendering is straight-line code.
 */
function compileTemplate(nodes, templates) {
  let uid = 0;
  const parts = [];
  const scope = [];
  const lookupExpr = (path) => {
    let e = null;
    for (let k = scope.length - 1; k >= 0; k--) {
      const v = scope[k].get(path[0]);
      if (v !== undefined) { e = v; break; }
    }
    if (e === null) e = `V.${path[0]}`;
    for (let k = 1; k < path.length; k++) e += `?.${path[k]}`;
    return e;
  };
  const gen = (ns, depth) => {
    for (const n of ns) {
      if (n.kind === 'text') parts.push(`_a.push(${JSON.stringify(n.text)});`);
      else if (n.kind === 'var') parts.push(`_a.push(escText(${lookupExpr(n.path)}));`);
      else if (n.kind === 'raw') parts.push(`_a.push(textOf(${lookupExpr(n.path)}));`);
      else if (n.kind === 'if') {
        const e = lookupExpr(n.path);
        parts.push(`if(${n.not ? '!' : ''}truthy(${e})){`);
        gen(n.then, depth);
        if (n.else !== null) { parts.push('}else{'); gen(n.else, depth); }
        parts.push('}');
      } else if (n.kind === 'for') {
        const e = lookupExpr(n.path);
        const xs = `_x${uid++}`;
        const ix = `_i${uid++}`;
        const el = `_e${uid++}`;
        const lp = `_l${uid++}`;
        const useLoop = refsLoop(n.body, depth, templates);
        if (useLoop) parts.push(`{const ${xs}=(${e});if(Array.isArray(${xs})){for(let ${ix}=0;${ix}<${xs}.length;${ix}++){const ${el}=${xs}[${ix}];const ${lp}={index:${ix}+1,first:${ix}===0,last:${ix}===${xs}.length-1,length:${xs}.length};`);
        else parts.push(`{const ${xs}=(${e});if(Array.isArray(${xs})){for(let ${ix}=0;${ix}<${xs}.length;${ix}++){const ${el}=${xs}[${ix}];`);
        const frame = new Map();
        frame.set(n.name, el);
        frame.set('loop', useLoop ? lp : 'EMPTY');
        scope.push(frame);
        gen(n.body, depth);
        scope.pop();
        parts.push('}}}');
      } else if (n.kind === 'include') {
        const t = templates.get(n.name);
        if (t !== undefined && depth < 8) gen(t, depth + 1);
      }
    }
  };
  gen(nodes, 0);
  return new Function('V', 'escText', 'textOf', 'truthy', 'EMPTY', `let _a=[];\n${parts.join('\n')}\nreturn _a.join("");`);
}

